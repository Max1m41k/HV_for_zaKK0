    public enum Mode { EN, RU }

    public static Mode mode = Mode.EN;

    private static final Map<String, String[]> RU = new HashMap<>();
    private static final Map<String, String> CATEGORY_RU = new HashMap<>();

    private Lang() {}

    private static void put(String key, String name, String description) {
        RU.put(key, new String[]{name, description});
    }

    /** Language applies purely from the mode; the Language module is only a settings holder. */
    public static boolean isRu() { return mode == Mode.RU; }

    public static String name(String key) {
        if (!isRu()) return key;
        String[] v = RU.get(key);
        return v == null || v[0].isEmpty() ? key : v[0];
    }

    public static String description(String key, String english) {
        if (english == null) english = "";
        if (!isRu()) return english;
        String[] v = RU.get(key);
        return v == null || v[1].isEmpty() ? english : v[1];
    }

    public static String category(String englishDisplayName) {
        if (!isRu()) return englishDisplayName;
        String v = CATEGORY_RU.get(englishDisplayName);
        return v == null ? englishDisplayName : v;
    }

    /** Both spellings so a search box matches whichever language is active. */
    public static boolean matches(String needle, String raw, String translated, String description) {
        if (needle == null || needle.isEmpty()) return true;
        String n = needle.toLowerCase();
        return contains(n, raw) || contains(n, translated) || contains(n, description);
    }

    private static boolean contains(String needle, String value) {
        return value != null && value.toLowerCase().contains(needle);
    }

